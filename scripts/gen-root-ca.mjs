// Regenerate firmware/common/root_ca.h from official root CA PEMs.
//   node scripts/gen-root-ca.mjs            (downloads the PEMs)
// Then run `npm run firmware:sync`. Needed only if Cloudflare switches certificate authority.
import { writeFileSync } from 'node:fs';
import { X509Certificate } from 'node:crypto';

const SOURCES = [
  'https://letsencrypt.org/certs/isrgrootx1.pem',
  'https://letsencrypt.org/certs/isrg-root-x2.pem',
  'https://i.pki.goog/r1.pem',
  'https://i.pki.goog/r4.pem',
];

const pems = [];
for (const url of SOURCES) {
  const pem = (await (await fetch(url)).text()).replace(/\r/g, '').trim();
  const cert = new X509Certificate(pem);  // throws if not a valid certificate
  if (!cert.ca) throw new Error(`${url} is not a CA certificate`);
  console.log(`${cert.subject.split('\n').find((l) => l.startsWith('CN='))}  valid to ${cert.validTo}`);
  pems.push(pem);
}

const body = pems.join('\n').split('\n').map((line) => `  "${line}\\n"`).join('\n');
writeFileSync(new URL('../firmware/common/root_ca.h', import.meta.url), [
  "// Root CAs that can sign *.pages.dev certificates (Cloudflare uses Let's Encrypt or Google Trust Services).",
  '// Generated by scripts/gen-root-ca.mjs from letsencrypt.org/certs (ISRG Root X1, X2) and i.pki.goog (GTS Root R1, R4).',
  '// Used with WiFiClientSecure::setCACert so the box verifies it is really talking to our API.',
  '#pragma once',
  'static const char ROOT_CA_BUNDLE[] PROGMEM =',
  body + ';',
  '',
].join('\n'));
console.log('wrote firmware/common/root_ca.h');
