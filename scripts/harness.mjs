// HomeBeacon harness tooling: generated docs, knowledge bundle, pack preview and evals.
//   node scripts/harness.mjs <thresholds|runbook|knowledge|pack|eval|sync|check> [flags]
// Also reachable as: npm run hb -- harness <subcommand>. Never prints key values.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const rel = p => join(ROOT, p);

export const FILES = Object.freeze({
  thresholds: 'docs/THRESHOLDS.md',
  runbook: 'docs/RUNBOOK.md',
  knowledge: 'src/harness/knowledge-data.js',
});

// ---------- knowledge bundle (so the Worker never reads files) ----------
export function knowledgeDir(root = ROOT) { return join(root, 'domain/knowledge'); }
export function readKnowledge(root = ROOT) {
  const dir = knowledgeDir(root), out = {};
  for (const f of readdirSync(dir).filter(x => x.endsWith('.md')).sort()) out[f.replace(/\.md$/, '')] = readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n').trimEnd();
  return out;
}
export function renderKnowledgeModule(root = ROOT) {
  const body = Object.entries(readKnowledge(root)).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
  return `// Generated by \`npm run hb -- harness knowledge --write\` from domain/knowledge/*.md. Do not edit by hand.\n// The Worker bundle has no file access, so the curated knowledge ships as data.\nexport const KNOWLEDGE = Object.freeze({\n${body}\n});\n`;
}

// ---------- generated docs ----------
async function generated(kind) {
  if (kind === 'knowledge') return renderKnowledgeModule();
  if (kind === 'thresholds') return (await import('../src/harness/thresholds.js')).renderThresholdsDoc();
  if (kind === 'runbook') return (await import('../src/harness/runbook.js')).renderRunbookDoc();
  throw new Error(`unknown generated file ${kind}`);
}
export async function syncStatus(kind) {
  const path = rel(FILES[kind]);
  const want = await generated(kind);
  const have = existsSync(path) ? readFileSync(path, 'utf8') : null;
  return { kind, path: FILES[kind], inSync: have === want, want };
}

// ---------- eval cases ----------
export function loadCases(dir = rel('test/fixtures/harness')) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter(f => f.endsWith('.json')).sort().flatMap(f => {
    const data = JSON.parse(readFileSync(join(dir, f), 'utf8'));
    return (Array.isArray(data) ? data : data.cases || []).map(c => ({ ...c, file: f }));
  });
}

// ---------- CLI ----------
function parseFlags(args) {
  const flags = {}, rest = [];
  for (let i = 0; i < args.length; i++) {
    const a = args[i];
    if (a.startsWith('--')) {
      const [k, v] = a.slice(2).split('=');
      if (v !== undefined) flags[k] = v;
      else if (args[i + 1] && !args[i + 1].startsWith('--') && ['budget', 'max-calls', 'max-tokens', 'category', 'purpose'].includes(k)) flags[k] = args[++i];
      else flags[k] = true;
    } else rest.push(a);
  }
  return { flags, rest };
}

/** Loads only NVIDIA_* names from process env, then .env / .dev.vars. Never prints values. */
export function nvidiaEnv(base = process.env, { files = true } = {}) {
  const env = {};
  const pick = src => { for (const [k, v] of Object.entries(src)) if (/^NVIDIA_(API_KEY|BASE_URL|MODEL)$/.test(k) && v && env[k] === undefined) env[k] = v; };
  pick(base);
  for (const file of files ? ['.env', '.dev.vars'] : []) {
    const path = rel(file);
    if (!existsSync(path)) continue;
    const parsed = {};
    for (const raw of readFileSync(path, 'utf8').split(/\r?\n/)) {
      const m = raw.trim().match(/^(?:export\s+)?(NVIDIA_[A-Z_]+)\s*=\s*(.*)$/);
      if (m) parsed[m[1]] = m[2].trim().replace(/^(['"])(.*)\1$/, '$2').replace(/\s+#.*$/, '');
    }
    pick(parsed);
  }
  return env;
}

export async function run(argv, io = {}) {
  const log = io.log || (m => console.log(m)), json = io.json || (o => console.log(JSON.stringify(o, null, 2)));
  const { flags, rest } = parseFlags(argv);
  const sub = rest[0];
  const usage = 'harness <thresholds|runbook|knowledge|pack|eval|sync|check> [--write] [--json]\n  thresholds|runbook|knowledge  print or --write / --check the generated file\n  pack [qa|view|agent] [--budget N] [--json]  show the grounding pack\n  eval [--live] [--max-calls N] [--max-tokens N] [--category X] [--json]  run golden cases (dry unless --live)\n  sync   regenerate all generated files\n  check  fail if a generated file differs from the code';
  if (!sub || flags.help) { log(usage); return sub ? 0 : 2; }

  if (['thresholds', 'runbook', 'knowledge'].includes(sub)) {
    const s = await syncStatus(sub);
    if (flags.write) { writeFileSync(rel(s.path), s.want); log(`wrote ${s.path}`); return 0; }
    if (flags.check) { log(s.inSync ? `${s.path} is up to date` : `${s.path} differs from the code. Run: npm run hb -- harness ${sub} --write`); return s.inSync ? 0 : 1; }
    log(s.want);
    return 0;
  }
  if (sub === 'sync') {
    // knowledge first: the pack imports it, and the docs do not.
    for (const k of ['knowledge', 'thresholds', 'runbook']) { const s = await syncStatus(k); writeFileSync(rel(s.path), s.want); log(`wrote ${s.path}`); }
    return 0;
  }
  if (sub === 'check') {
    let bad = 0;
    for (const k of ['knowledge', 'thresholds', 'runbook']) { const s = await syncStatus(k); log(`${s.inSync ? 'ok  ' : 'DIFF'} ${s.path}`); if (!s.inSync) bad++; }
    if (bad) log('Run: npm run hb -- harness sync');
    return bad ? 1 : 0;
  }
  if (sub === 'pack') {
    const { buildPack } = await import('../src/harness/pack.js');
    const purpose = rest[1] || flags.purpose || 'qa';
    const pack = buildPack({ purpose, budgetTokens: flags.budget ? Number(flags.budget) : undefined });
    if (flags.json) json({ version: pack.version, packId: pack.packId, purpose: pack.purpose, tokens: pack.tokens, budgetTokens: pack.budgetTokens, included: pack.included, omitted: pack.omitted });
    else { log(pack.text); log(`\n[${pack.packId}: ${pack.tokens} of ${pack.budgetTokens} tokens; included ${pack.included.join(', ')}${pack.omitted.length ? `; omitted ${pack.omitted.join(', ')}` : ''}]`); }
    return 0;
  }
  if (sub === 'eval') {
    const { runDry, runLive, liveConfig } = await import('../src/harness/eval.js');
    let cases = loadCases();
    if (flags.category) cases = cases.filter(c => c.category === flags.category);
    if (!cases.length) { log('No golden cases found in test/fixtures/harness/.'); return 2; }
    const report = flags.live ? await runLive(cases, nvidiaEnv(io.env || process.env, { files: !io.noFiles }), { maxCalls: flags['max-calls'] ? Number(flags['max-calls']) : undefined, maxTotalTokens: flags['max-tokens'] ? Number(flags['max-tokens']) : undefined }) : runDry(cases);
    if (flags.json) json(report);
    else {
      if (flags.live && !report.ran) log(`LIVE NOT RUN: ${report.reason}`);
      else {
        for (const r of report.results) log(`${r.pass ? 'PASS' : 'FAIL'}  ${r.id}${r.pass ? '' : `\n      ${r.failures.join('\n      ')}`}`);
        log(`${report.mode} mode: ${report.passed}/${report.total} passed${report.model ? ` (model ${report.model})` : ''}`);
        if (!flags.live) { const c = liveConfig(nvidiaEnv(io.env || process.env, { files: !io.noFiles })); log(c.configured ? 'Live model is configured: run with --live to check real answers.' : 'No NVIDIA key or endpoint is configured, so live mode cannot run here.'); }
      }
    }
    if (flags.live && !report.ran) return 3;
    return report.passed === report.total ? 0 : 1;
  }
  log(`Unknown subcommand "${sub}".\n${usage}`);
  return 2;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  run(process.argv.slice(2)).then(code => { process.exitCode = code; }, e => { console.error(e.message); process.exitCode = 1; });
}
