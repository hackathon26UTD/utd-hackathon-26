// One-command ESP-NOW mesh test: plug in two ESP32 boards, then
//   npm run mesh-test                 detect, configure, flash both, watch for 60 s, report PASS/FAIL
//   npm run mesh-test -- --watch 120  watch longer (seconds)
//   npm run mesh-test -- --no-flash   just watch boards that are already flashed
//
// Box A (gateway) = first board found, box B = second. If WIFI_SSID/WIFI_PASS are in .env, box A
// joins that hotspot and is a real Wi-Fi gateway; otherwise box A is forced to act as gateway so
// the mesh can be tested with no hotspot at all.
import { spawn, spawnSync } from 'node:child_process';
import { existsSync, readdirSync, writeFileSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { homedir } from 'node:os';
import { env } from './env.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SKETCH = join(ROOT, 'firmware', 'mesh_test');
const CONFIG = join(SKETCH, 'mesh_test_config.h');
const args = process.argv.slice(2);
const watchSeconds = Number(args[args.indexOf('--watch') + 1]) || 60;
const noFlash = args.includes('--no-flash');

const CLI = [process.env.ARDUINO_CLI, 'C:/Program Files/Arduino CLI/arduino-cli.exe'].find((p) => p && existsSync(p)) || 'arduino-cli';
function findEsptool() {
  const base = join(process.env.LOCALAPPDATA || join(homedir(), 'AppData/Local'), 'Arduino15/packages/esp32/tools/esptool_py');
  if (!existsSync(base)) return 'esptool';
  for (const v of readdirSync(base).sort().reverse()) for (const name of ['esptool.exe', 'esptool']) if (existsSync(join(base, v, name))) return join(base, v, name);
  return 'esptool';
}
const ESPTOOL = findEsptool();
const FQBN = { 'ESP32-S3': 'esp32:esp32:XIAO_ESP32S3', 'ESP32': 'esp32:esp32:esp32', 'ESP32-C3': 'esp32:esp32:esp32c3', 'ESP32-C6': 'esp32:esp32:esp32c6', 'ESP32-S2': 'esp32:esp32:esp32s2' };

const run = (cmd, a, opts = {}) => spawnSync(cmd, a, { encoding: 'utf8', ...opts });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

function serialPorts() {
  const r = run(CLI, ['board', 'list', '--format', 'json']);
  try {
    const j = JSON.parse(r.stdout);
    const list = Array.isArray(j) ? j : j.detected_ports || [];
    return list.map((d) => d.port || d).filter((p) => p.protocol === 'serial' && p.address).map((p) => p.address);
  } catch { return []; }
}

// Ask the chip itself (read-only): chip family and base MAC (= Wi-Fi station MAC on ESP32/S3).
function probe(port) {
  const r = run(ESPTOOL, ['--port', port, 'read-mac'], { timeout: 40000 });
  const out = `${r.stdout}\n${r.stderr}`;
  const chip = (out.match(/Detecting chip type\.\.\.\s*(ESP32[-\w]*)/) || [])[1];
  const mac = (out.match(/MAC:\s*([0-9a-f:]{17})/i) || [])[1];
  return chip && mac ? { port, chip, mac: mac.toUpperCase() } : null;
}

async function findBoards() {
  const deadline = Date.now() + 120000; let told = false;
  while (Date.now() < deadline) {
    const boards = [];
    for (const p of serialPorts().sort()) { const b = probe(p); if (b) boards.push(b); }
    if (boards.length >= 2) return boards.slice(0, 2);
    if (!told) { console.log(`Found ${boards.length} ESP32 board(s)${boards.map((b) => ` [${b.chip} on ${b.port}]`).join('')}. Plug in ${2 - boards.length} more (waiting up to 2 min)...`); told = true; }
    await sleep(4000);
  }
  throw new Error('Need two ESP32 boards plugged in by USB. Check the cables carry data (some are charge-only).');
}

const q = (s) => JSON.stringify(String(s));
function writeConfig(id, boards, { ssid, pass, force }) {
  writeFileSync(CONFIG, [
    '// Generated by scripts/mesh-test.mjs for one board. Git-ignored.',
    `#define MY_NODE_ID ${q(id)}`, `#define MAC_A ${q(boards[0].mac)}`, `#define MAC_B ${q(boards[1].mac)}`,
    `#define WIFI_SSID ${q(ssid)}`, `#define WIFI_PASS ${q(pass)}`, `#define FORCE_GATEWAY ${force ? 1 : 0}`, '',
  ].join('\n'));
}

function flash(board, id) {
  const fqbn = FQBN[board.chip];
  if (!fqbn) throw new Error(`No build target for ${board.chip}`);
  console.log(`\n▶ Flashing box ${id} (${board.chip}, ${board.port}) ... compile can take a few minutes the first time`);
  const r = run(CLI, ['compile', '--upload', '-p', board.port, '--fqbn', fqbn, '--build-path', join(ROOT, 'firmware', '.build', `mesh_test_${id}`), SKETCH], { stdio: 'inherit' });
  if (r.status !== 0) throw new Error(`Flashing box ${id} failed. XIAO tip: hold BOOT, tap RESET, release BOOT, then rerun.`);
}

function watch(boards, seconds) {
  return new Promise((resolve) => {
    const stats = { A: { gotFromB: 0, acks: 0, waiting: 0, gateway: false, lines: 0 }, B: { gotFromA: 0, acks: 0, waiting: 0, gateway: false, lines: 0 } };
    const procs = boards.map((b, i) => {
      const id = i === 0 ? 'A' : 'B', other = id === 'A' ? 'B' : 'A', s = stats[id];
      const p = spawn(CLI, ['monitor', '-p', b.port, '-c', 'baudrate=115200', '--quiet']);
      let buf = '';
      p.stdout.on('data', (d) => {
        buf += d.toString();
        let i2; while ((i2 = buf.indexOf('\n')) >= 0) {
          const line = buf.slice(0, i2).replace(/\r$/, ''); buf = buf.slice(i2 + 1);
          if (!line.trim()) continue;
          s.lines++;
          console.log(`${id === 'A' ? '\x1b[36m[A]\x1b[0m' : '\x1b[33m[B]\x1b[0m'} ${line}`);
          if (new RegExp(`GATEWAY got .* from box ${other}\\b`).test(line)) s[`gotFrom${other}`]++;
          if (/<<< ACK from gateway/.test(line)) s.acks++;
          if (/this box is (the|a) GATEWAY/.test(line)) s.gateway = true;
          const w = line.match(/waiting for ACK: (\d+)/); if (w) s.waiting = Number(w[1]);
        }
      });
      return p;
    });
    console.log(`\n── Watching both boards for ${seconds} s (Ctrl+C to stop early) ──`);
    setTimeout(() => { procs.forEach((p) => p.kill()); resolve(stats); }, seconds * 1000);
  });
}

try {
  console.log(`arduino-cli: ${CLI}\nesptool:     ${ESPTOOL}\nLooking for ESP32 boards...`);
  const boards = await findBoards();
  boards.forEach((b, i) => console.log(`  box ${i ? 'B' : 'A'}: ${b.chip} on ${b.port}, MAC ${b.mac}${i ? '' : '  (gateway)'}`));
  const ssid = env.WIFI_SSID || '', pass = env.WIFI_PASS || '';
  const force = !(ssid && pass);
  console.log(force ? '  No WIFI_SSID/WIFI_PASS in .env: box A will act as gateway without Wi-Fi (mesh-only test).' : `  Box A joins hotspot "${ssid}"; box B uses it only to find the channel.`);

  if (!noFlash) {
    try {
      writeConfig('A', boards, { ssid, pass, force }); flash(boards[0], 'A');
      writeConfig('B', boards, { ssid, pass: '', force: false }); flash(boards[1], 'B');
    } finally { rmSync(CONFIG, { force: true }); }
  }

  const s = await watch(boards, watchSeconds);
  const meshOk = s.A.gotFromB > 0 && s.B.acks > 0;
  console.log('\n══════════ RESULT ══════════');
  console.log(`Box A (gateway): received ${s.A.gotFromB} hello(s) from box B over the encrypted mesh`);
  console.log(`Box B: got ${s.B.acks} ACK(s) back from the gateway; ${s.B.waiting} still waiting at last report`);
  if (meshOk) console.log('PASS: encrypted ESP-NOW mesh works in both directions (data B -> A, ACK A -> B).');
  else if (!s.A.lines || !s.B.lines) console.log('FAIL: no serial output from a board. Unplug/replug it and run `npm run mesh-test -- --no-flash`.');
  else if (s.A.gotFromB === 0) console.log('FAIL: box A heard nothing from box B. Likely different channels (hotspot not visible to B) or boards too far apart.');
  else console.log('FAIL: data reached A but ACKs did not reach B. Run again; if it persists, check range/interference.');
  console.log('Next: turn the hotspot off/on (or unplug box A) and rerun with --no-flash --watch 120 to see store-and-forward.');
  process.exit(meshOk ? 0 : 1);
} catch (e) {
  console.error(`\n${e.message}`);
  process.exit(1);
}
